import { test, expect } from '../harness/fixtures';
import { ui } from '../harness/ui';

// Publishing is the one place Bazel writes to GitHub. Here "GitHub" is the
// fake gh's call log: every assertion is on the exact argv and payload that
// would have gone out.

async function openFinishedReview(app: any, bazel: any) {
  const id = await bazel.enqueue('acme/api-core#101', 'review-fleet');
  await bazel.waitJob(id, (j: any) => j.state === 'done');
  await app.reload();
  await ui.jobCard(app, 'Add rate limiter to the public API').click();
  const viewer = ui.viewer(app);
  await expect(viewer.getByText('E2E-FINDING-TWO')).toBeVisible();
  return { id, viewer };
}

test.describe('P0 · publish', () => {
  test('"paste as a comment" sends gh pr comment without the unticked finding', async ({ app, bazel }) => {
    const { id, viewer } = await openFinishedReview(app, bazel);
    const dialogs: string[] = [];
    app.on('dialog', (d) => dialogs.push(d.message()));

    await ui.findingPicks(viewer).nth(1).uncheck(); // F2 stays out
    await ui.pasteAsComment(viewer).click();
    await bazel.waitJob(id, (j) => j.posted === true);

    const comments = bazel.ghCalls().filter((c) => c.argv[0] === 'pr' && c.argv[1] === 'comment');
    expect(comments).toHaveLength(1);
    expect(comments[0].argv).toEqual(['pr', 'comment', '101', '--repo', 'acme/api-core', '--body-file', '-']);
    const body = comments[0].stdin;
    expect(body.startsWith('## 🥚 Automated review — Bazel\n\n')).toBe(true);
    expect(body).toContain('E2E-FINDING-ONE');
    expect(body).not.toContain('E2E-FINDING-TWO');
    expect(body).toMatch(/<sub>Generated by \[Bazel\]\(https:\/\/github\.com\/beroni\/bazel\) at .* · review-fleet<\/sub>\n$/);
    // No agent ran to publish: the comment path is Bazel itself.
    expect(bazel.agentCalls().map((c) => c.scenario)).toEqual(['claude-findings']);

    await expect(viewer.getByText('✓ already on the PR')).toBeVisible();
    // A second post is refused (409), not sent twice.
    const again = await bazel.api('POST', `/api/jobs/${id}/post`, {});
    expect(again.status).toBe(409);
    expect(bazel.ghCalls().filter((c) => c.argv[1] === 'comment')).toHaveLength(1);
  });

  test('"publish inline review" runs the post agent, which calls gh with the trimmed review', async ({ app, bazel }) => {
    const { id, viewer } = await openFinishedReview(app, bazel);
    await ui.findingPicks(viewer).nth(0).uncheck(); // F1 stays out this time
    await ui.publishInline(viewer).click();
    const job = await bazel.waitJob(id, (j) => j.posted === true || !!j.post_error, 20_000);
    expect(job.post_error ?? '').toBe('');

    // The post agent ran in a fresh clone, with the built-in skill materialized
    // and the copy without F1 as its review file.
    const post = bazel.agentCalls().find((c) => c.scenario === 'post-claude');
    expect(post).toBeTruthy();
    expect(post!.builtin_skill).toBe(true);
    const reviewFile = post!.prompt.match(/\/bazel-post-report\s+(\S+)/)![1];
    expect(reviewFile).toContain(`${bazel.reviewsDir}/publish/`);

    const reviews = bazel.ghCalls().filter((c) => c.argv[0] === 'api' && c.argv.includes('repos/acme/api-core/pulls/101/reviews'));
    expect(reviews).toHaveLength(1);
    expect(reviews[0].argv).toEqual(['api', '--method', 'POST', 'repos/acme/api-core/pulls/101/reviews', '--input', '-']);
    const payload = JSON.parse(reviews[0].stdin);
    expect(payload.event).toBe('COMMENT');
    expect(payload.body).toContain('# acme/api-core#101 — Add rate limiter to the public API');
    expect(payload.body).not.toContain('E2E-FINDING-ONE');
    expect(payload.body).toContain('E2E-FINDING-TWO');

    // Bazel itself sent nothing: no gh pr comment on this path.
    expect(bazel.ghCalls().some((c) => c.argv[1] === 'comment')).toBe(false);
    await expect(viewer.getByText('✓ already on the PR')).toBeVisible();
    await expect(ui.jobCard(app, 'Add rate limiter to the public API').getByText('✓ published')).toBeVisible();
  });
});
